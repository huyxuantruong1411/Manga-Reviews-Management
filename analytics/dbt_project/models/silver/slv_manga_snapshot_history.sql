with dedup_raw as (
    select
        _source_id as manga_id,
        _snapshot_date as snapshot_date,
        _ingested_at as ingested_at,
        _batch_id as batch_id,
        _document_hash as document_hash,
        _document_ejson
    from {{ ref('brz_mangas') }}
    qualify row_number() over (
        partition by _source_id, _snapshot_date
        order by _ingested_at desc
    ) = 1
),
base as (
    select
        manga_id,
        snapshot_date,
        ingested_at,
        batch_id,
        document_hash,
        {{ ejson_str('_document_ejson', '$.title') }} as manga_title_raw,
        {{ ejson_str('_document_ejson', '$.mangadex_id') }} as mangadex_id,
        {{ normalize_read_status(ejson_str('_document_ejson', '$.read_status')) }} as read_status,
        {{ ejson_str('_document_ejson', '$.read_status') }} as read_status_raw,
        {{ normalize_pub_status(ejson_str('_document_ejson', '$.status')) }} as publication_status,
        {{ ejson_str('_document_ejson', '$.status') }} as publication_status_raw,
        {{ ejson_str('_document_ejson', '$.content_rating') }} as content_rating,
        {{ ejson_str('_document_ejson', '$.publication_demographic') }} as publication_demographic,
        {{ ejson_str('_document_ejson', '$.original_language') }} as original_language,
        try_cast({{ ejson_str('_document_ejson', '$.year') }} as integer) as publication_year,
        {{ ejson_str('_document_ejson', '$.year') }} as publication_year_raw,
        {{ ejson_str('_document_ejson', '$.published_start_date') }} as published_start_date,
        {{ ejson_str('_document_ejson', '$.published_end_date') }} as published_end_date,
        {{ ejson_double('_document_ejson', '$.personal_rating') }} as personal_rating,
        {{ ejson_int('_document_ejson', '$.chapters') }} as declared_chapters,
        {{ ejson_int('_document_ejson', '$.volumes') }} as declared_volumes,
        coalesce({{ ejson_bool('_document_ejson', '$.is_deleted') }}, false) as is_deleted,
        {{ ejson_ts('_document_ejson', '$.added_at') }} as added_at,
        {{ ejson_ts('_document_ejson', '$.updated_at') }} as updated_at,
        {{ ejson_ts('_document_ejson', '$.unread_at') }} as unread_at,
        {{ ejson_ts('_document_ejson', '$.reading_at') }} as reading_at,
        {{ ejson_ts('_document_ejson', '$.completed_at') }} as completed_at,
        {{ ejson_ts('_document_ejson', '$.dropped_at') }} as dropped_at,
        {{ ejson_ts('_document_ejson', '$.on_hold_at') }} as on_hold_at,
        {{ ejson_ts('_document_ejson', '$.plan_to_read_at') }} as plan_to_read_at,
        {{ ejson_ts('_document_ejson', '$.re_reading_at') }} as re_reading_at,
        {{ ejson_double('_document_ejson', '$.tracker_metadata.mal.score') }} as tracker_mal_score,
        {{ ejson_double('_document_ejson', '$.tracker_metadata.mal_extended.score') }} as tracker_mal_extended_score,
        {{ ejson_int('_document_ejson', '$.tracker_metadata.mal_extended.scored_by') }} as tracker_mal_scored_by,
        {{ ejson_ts('_document_ejson', '$.tracker_metadata.mal.last_synced_at') }} as tracker_mal_last_synced_at,
        {{ ejson_int('_document_ejson', '$.tracker_metadata.anilist.mean_score') }} as tracker_anilist_mean_score,
        {{ ejson_int('_document_ejson', '$.tracker_metadata.anilist.average_score') }} as tracker_anilist_average_score,
        {{ ejson_ts('_document_ejson', '$.tracker_metadata.fetched_at') }} as tracker_fetched_at,
        {{ ejson_int('_document_ejson', '$.metadata_revision') }} as metadata_revision,
        case when json_extract(_document_ejson, '$.metadata_locks') is not null then json_array_length(json_keys(json_extract(_document_ejson, '$.metadata_locks'))) else 0 end as metadata_lock_count,
        case when json_extract(_document_ejson, '$.metadata_provenance') is not null then json_array_length(json_keys(json_extract(_document_ejson, '$.metadata_provenance'))) else 0 end as metadata_provenance_count,
        (nullif({{ ejson_str('_document_ejson', '$.author') }}, '') is not null) as has_legacy_author,
        (nullif({{ ejson_str('_document_ejson', '$.artist') }}, '') is not null) as has_legacy_artist,
        coalesce(json_array_length(json_extract(_document_ejson, '$.tag_ids')), 0) as tag_count_raw,
        coalesce(json_array_length(json_extract(_document_ejson, '$.creators')), 0) as creator_ref_count_raw
    from dedup_raw
)
select
    manga_id,
    snapshot_date,
    ingested_at,
    batch_id,
    document_hash,
    manga_title_raw,
    mangadex_id,
    read_status,
    read_status_raw,
    publication_status,
    publication_status_raw,
    content_rating,
    publication_demographic,
    original_language,
    publication_year,
    publication_year_raw,
    published_start_date,
    published_end_date,
    personal_rating,
    case
        when personal_rating is null then true
        when personal_rating >= 0.0 and personal_rating <= 10.0 and abs((personal_rating * 2.0) - round(personal_rating * 2.0)) < 1e-6 then true
        else false
    end as rating_is_valid,
    declared_chapters,
    declared_volumes,
    is_deleted,
    added_at,
    updated_at,
    unread_at,
    reading_at,
    completed_at,
    dropped_at,
    on_hold_at,
    plan_to_read_at,
    re_reading_at,
    coalesce(tracker_mal_extended_score, tracker_mal_score) as tracker_mal_score,
    tracker_mal_scored_by,
    tracker_mal_last_synced_at,
    tracker_anilist_mean_score,
    tracker_anilist_average_score,
    tracker_fetched_at,
    metadata_revision,
    metadata_lock_count,
    metadata_provenance_count,
    has_legacy_author,
    has_legacy_artist,
    tag_count_raw,
    creator_ref_count_raw
from base
